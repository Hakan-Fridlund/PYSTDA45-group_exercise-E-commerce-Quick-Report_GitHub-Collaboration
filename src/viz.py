import pandas as pd 
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path

#Huvud class
class base_viz:
      def __init__(self, df):
            #En kopia av data
            self.data = df.copy()

      def prepare_data(self):
            #kopia för inte skada orginal
            data = self.data.copy()

            ##sammanfätta column namn
            data.columns = data.columns.str.strip()

            #konvert datan till datetime
            data["date"] = pd.to_datetime(data["date"], errors="coerce")

            #konvert numeric columns
            for column in["price", "units"]:
                  data[column] = pd.to_numeric(data[column], errors="coerce")

            #räkna revenue
            data["revenue"] = data["price"] * data["units"]

            return data 

class Ecommerce_viz(base_viz):
      
      #Revenue per kategorier
      def plot_revenue_by_category(self):
           data = self.prepare_data()
           data = data.dropna(subset=["category", "revenue"])

           category_revenue =(data.groupby("category")["revenue"].sum().sort_values(ascending=False)) 

           #Skappa stapeldiagram
           fig, ax = plt.subplots(figsize=(10, 6))

           category_revenue.plot(
           kind="bar",
           ax=ax,
           color=["steelblue", "orange", "seagreen", "coral", "mediumpurple"],
           capsize=10,
           yerr=4)

           

           #Lägga till rubrik och axelrubrik och diagramets layout     
           fig.text(0.5, 0.90, "This chart shows the revenue generated by each category.\n""Purpose: to compare revenue across produkt category.",
                    transform=ax.transAxes,
                    ha="center",
                    va="bottom",
                    fontsize=10,
                    fontweight="bold")
           ax.set_title("Revenue by Category", fontweight="bold")
           ax.set_ylabel("Revenue (kr)", fontweight="bold")
           ax.set_xlabel("Category", fontweight="bold")
           ax.grid(True, axis="y", alpha=0.3)  
           plt.xticks(rotation=45, ha="right")
           plt.tight_layout()
           #plt.subplots_adjust()
           
           #visa diagramet
           plt.show()

           return ax

      def plot_revenue_by_city(self):
            data = self.prepare_data()
            data = data.dropna(subset=["city", "revenue"])

            city_revenue=(data.groupby("city")["revenue"].sum().sort_values(ascending=True))      

            #skapa diagrammet
            fig, ax =plt.subplots(figsize=(10, 6))

            city_revenue.plot(
                  kind="bar",
                  figsize=(10, 5),
                  color=["seagreen", "mediumpurple", "coral", "steelblue", "orange"],
                  capsize=10,
                  yerr=4)
            fig.text(0.5, .90, "This chart shows the revenue generated by each city.\n""Purpose: To compare sales performanceacross cities.",
                     transform=ax.transAxes,
                     ha="center",
                     va="bottom",
                     fontsize=9,
                     fontweight="bold")
            
            #Lägga till rubriker
            ax.set_title("Revenue by city", fontweight="bold")
            ax.set_ylabel("Revenue (kr)", fontweight="bold")
            ax.set_xlabel("city", fontweight="bold")
            ax.grid(True, axis="y")
            plt.xticks(rotation=45, ha="right")
            plt.tight_layout()

            #Visa diagrammet
            plt.show()

            return ax
      
      def plot_revenue_over_time(self):
            data = self.prepare_data()
            data = data.dropna(subset=["date", "revenue"])
            data = data.sort_values("date")
            data = data.set_index("date")

            monthly_revenue = data["revenue"].resample("MS").sum()
            
            fig, ax = plt.subplots(figsize=(10, 6))

            #Skappa linjediagrammet
            ax.plot(monthly_revenue.index,
                    monthly_revenue.values,
                  marker="o",
                  color="darkorange",
                  linestyle=":",
                  linewidth=2,
                  label="Månadsintäkt" )
            
            # räkna trenlinjen
            x = np.arange(len(monthly_revenue))
            y = monthly_revenue.values
            
            if len(x) > 1:
                      slope, intercept = np.polyfit(x, y, 1)
                      trendline = slope * x + intercept
            
                      # lägga till trendlinjen
                      ax.plot(
                           monthly_revenue.index,
                           trendline,
                           color="blue",
                           linestyle="--", 
                           linewidth=2,
                           label="Trendlinje")
                      
            #lägg till månader namn
            ax.set_xticks(monthly_revenue.index)
            ax.set_xticklabels(monthly_revenue.index.strftime("%b %Y"), rotation=45, ha="right")

            #Lägga till rubrik, axelrubriker och diagrammets layout
            fig.text(0.5, 1.16, "This chart shows how revenue changes over time.\n""Purpose: To identify revenue trends across months",
                     transform=ax.transAxes, ha="center", fontsize=10, fontweight="bold")
            ax.set_title("Monthly Revenue over Time", fontweight="bold")
            ax.set_xlabel("month", fontweight="bold")
            ax.set_ylabel("Revenue (kr)", fontweight="bold")

            ax.grid(True, alpha=0.3)  
            ax.legend()    
            plt.xticks(rotation=45, ha="right")
            plt.tight_layout()

            fig.autofmt_xdate()
            fig.subplots_adjust(top=0.82)

            #Visa diagrammet
            plt.show()

      def plot_aov(self):
            data = self.prepare_data()
            data = data.dropna(subset=["order_id", "revenue"])

            #räkna intäkt per order
            order_revenue = data.groupby("order_id")["revenue"].sum()

            #Beräkna genomsnittligt ordervärde
            aov = order_revenue.mean()
            median_värde = order_revenue.median()

            print(f"AOV: {aov:.2f} kr")
            print(f"Median order value: {median_värde:.2f} kr")

            #boxplot
            fig, ax = plt.subplots(figsize=(10, 7))
            ax.boxplot(order_revenue, vert=False,
                       patch_artist=True,
                       boxprops=dict(facecolor="lightblue"),
                       medianprops=dict(color="darkblue", linewidth=2))

            #AOV line
            ax.axvline(aov, color="red", linestyle="--", label=f"AOV = {aov:.2f}")
            #Median line
            ax.axvline(median_värde, color="green", linestyle=":", label=f"Median= {median_värde:.2f}")

            #Text
            ax.text(0.5, 0.93, "This Boxplot shows the distripution of order value and highlights the mean, median and outliers.\n""Purpose: To understand the average value of customer orders",
                    transform=ax.transAxes, ha="center", fontsize=10, fontweight="bold")
     
            #Rubrik and axis namn
            ax.set_title("Average Order Value(AOV)",fontweight="bold", pad=65)
            ax.set_xlabel("Order value (sek)", fontweight="bold")
            ax.set_ylabel("Order Distribution", fontweight="bold")

            ax.set_yticks([1])
            ax.set_yticklabels(["Orders"])
            ax.legend(loc="best")
            ax.grid(True, axis="x", alpha=0.3)

            plt.tight_layout()
            fig.subplots_adjust(top=0.80)
            plt.show() 

            return ax    

      def plot_total_revenue_and_unit(self):
            data = self.prepare_data()
            data = data.dropna(subset=["revenue", "units"])

            #räkna total revenue, total unit
            total_revenue = data["revenue"].sum()
            total_unit = data["units"].sum()
            print("Total revenue: ", round(total_revenue, 2))
            print("Total units: ", round(total_unit, 2))

            #Skapa en nykeltal figur
            fig, axes = plt.subplots(1, 2, figsize=(14, 8))
            fig.suptitle("Total Revenue and Units Sold", fontsize=16, fontweight="bold", y=0.98)
            fig.text(0.5, 0.91,
                     "This chart shows total revenue and total units sold.\n""Purpose: To summarize overall sales sales performance.",
                     ha="center", fontsize=10, fontweight="bold")

            #diagrammet text
            axes[0].text(0.5, 0.5,
                         f"{total_revenue:,.0f} kr",
                         ha="center", va="center",
                         fontsize=20)

            #total intäkt
            axes[0].bar(["Total Revenue"], [total_revenue], color="lightblue", width=0.5)
            axes[0].set_title("Total Revenue", fontweight="bold")
            axes[0].set_ylabel("Revenue (kr)", fontweight="bold")
            axes[0].bar_label(axes[0].containers[0],
                              labels=[f"{total_revenue:,.0f} kr"],
                              padding=5)
            axes[0].grid(True, axis="y", alpha=0.3)
     
            #total enheter
            axes[1].bar(["Units Sold"], [total_unit], color="pink", width=0.5)
            axes[1].set_title("Total Units Sold", fontweight="bold")
            axes[1].set_ylabel("Number of Units", fontweight="bold")
            axes[1].bar_label(axes[1].containers[0],
                              labels=[f"{total_unit:,.0f}"],
                              padding=5)
            axes[1].grid(True, axis="y", alpha=0.3)

            fig.subplots_adjust(top=0.80, wspace=0.40)

            #Visa
            plt.tight_layout()
            plt.show()    

            return axes   

      def plot_top_3catotegories(self):
            data = self.prepare_data()
            data = data.dropna(subset=["category", "revenue"])

            #räkna intäkt per kategory och dem 3 högsta
            top_tre = (data.groupby("category")["revenue"].sum().sort_values(ascending=False).nlargest(3))
   
            #stapeldiagram
            fig, ax =plt.subplots(figsize=(8, 6))
            top_tre.plot(kind = "pie", ax=ax, colors=["teal", "indianred", "orange"], 
                         autopct="%1.1f%%",
                         startangle=90)
            fig.text(0.5, 0.90,
                     "This chart shows the three categories with the highest revenue.\n""Purpose: Identify the best performing product categories",
                     ha="center", fontsize=10, fontweight="bold")
            ax.set_title("Top 3 Categories by", fontweight="bold")
            ax.set_ylabel("")
            fig.subplots_adjust(top=0.82)

            plt.show()

            print("Top 3 categories: ", (top_tre.round(2)))
   
            return ax
            
